# Regenerates stubs/*.syms from a head unit's real HU Framework libraries (opt/hmi/ID5/lib in a firmware dump).
# Only needed when a firmware exports HU Framework symbols the lists don't have yet. Needs readelf (binutils).
#
# usage: tools/update_stubs.sh <dir holding libAppFramework.A.so and libCoreFramework.A.so>
set -eu

[ $# -eq 1 ] || { echo "usage: $0 <dir with libAppFramework.A.so and libCoreFramework.A.so>" >&2; exit 1; }
src=$1
cd "$(dirname "$0")/.."

for lib in libAppFramework.A libCoreFramework.A; do
    [ -f "$src/$lib.so" ] || { echo "$0: no $lib.so in '$src'" >&2; exit 1; }
    out=stubs/$lib.syms
    {
        echo "# HU Framework: exported bmw:: symbols of $lib.so, names and kinds only (F = function, O = object)."
        echo "# The Makefile builds an empty link stub with this soname from the list, so no head-unit binary is needed to"
        echo "# build. Generated by tools/update_stubs.sh; do not edit by hand."
        readelf --dyn-syms -W "$src/$lib.so" |
            awk '$7 != "UND" && ($5 == "GLOBAL" || $5 == "WEAK") && $8 ~ /3bmw/ {
                     if ($4 == "FUNC") print "F " $8; else if ($4 == "OBJECT") print "O " $8 }' |
            LC_ALL=C sort -u
    } > "$out"
    echo "wrote $out ($(grep -c '^[FO] ' "$out") symbols)"
done
